"""Write a printable LaTeX sheet (and optionally the PDF) for a Song.

    ktab tex songs/ami_chini.ktab              # -> songs/ami_chini.tex + .pdf
    ktab tex song.ktab -o sheets/song.tex --no-pdf

Layout comes from optional header lines in the .ktab file:

    @title:    Ami Chini Go Chini Tomare     (default: the file name)
    @subtitle: Kalimba tab                   (default "Kalimba tab"; "none" hides it)
    @paper:    a4 | letter                   (default a4)
    @margin:   1.5cm                         page margins (default 1.5cm)
    @beat:     2.1em                         width of one beat (default 2.1em)
    @wordgap:  .8em                          space between words (default .8em)
    @linegap:  1.05em                        space between lines (default 1.05em)
    @stanzagap: 1.2em                        extra space between stanzas (default 1.2em)
    @align:    left | centre                 (default left)

Other headers are ignored here (other tools may use them).
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
from importlib import resources

from .model import Song

DEFAULTS = dict(subtitle="Kalimba tab", paper="a4", margin="1.5cm", beat="2.1em",
                wordgap=".8em", linegap="1.05em", stanzagap="1.2em", align="left")
_LENGTH = re.compile(r"^-?\d*\.?\d+\s*(em|ex|pt|mm|cm|in|bp)$")
_TEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
                "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
                "^": r"\textasciicircum{}"}


class LatexError(RuntimeError):
    pass


def escape(text: str) -> str:
    return "".join(_TEX_SPECIAL.get(c, c) for c in text)


def settings(song: Song, fallback_title: str) -> dict:
    s = dict(DEFAULTS, title=fallback_title)
    s.update({k: v for k, v in song.headers.items() if v})
    for key in ("margin", "beat", "wordgap", "linegap", "stanzagap"):
        if not _LENGTH.match(s[key].strip()):
            raise LatexError(f"@{key}: '{s[key]}' is not a length (write e.g. 1.5cm or .8em)")
    if s["paper"].lower() not in ("a4", "letter"):
        raise LatexError(f"@paper: '{s['paper']}' should be a4 or letter")
    if s["align"].lower() not in ("centre", "center", "left"):
        raise LatexError(f"@align: '{s['align']}' should be centre or left")
    return s


def _body(song: Song) -> str:
    """The tab in canonical form, lyrics escaped for TeX, stanzas split by blank lines."""
    out = []
    for st in song.stanzas:
        lines = []
        for ln in st.lines:
            text = str(ln)
            # escape only inside lyric text: "(lyric: notes)"
            text = re.sub(r"\(([^:()]*):", lambda m: "(" + escape(m.group(1)) + ":", text)
            lines.append(text)
        out.append("\n".join(lines))
    return "\n\n".join(out)


def to_tex(song: Song, fallback_title: str = "Untitled") -> str:
    s = settings(song, fallback_title)
    sub = "" if s["subtitle"].lower() == "none" else f"[{escape(s['subtitle'])}]"
    m = s["margin"]
    return "\n".join([
        "% generated by `ktab tex` -- edit the .ktab file and run it again",
        r"\documentclass[11pt]{article}",
        rf"\usepackage[{s['paper'].lower()}paper,top={m},bottom={m},left={m},right={m}]{{geometry}}",
        r"\usepackage{jianpu}",
        rf"\setlength{{\jpbeat}}{{{s['beat']}}}",
        rf"\setlength{{\jplinegap}}{{{s['linegap']}}}",
        rf"\setlength{{\jpstanzagap}}{{{s['stanzagap']}}}",
        rf"\renewcommand\jpwordsep{{\unskip\hskip {s['wordgap']} plus .4em\relax}}",
        r"\jpcentred" if s["align"].lower() in ("centre", "center") else "",
        r"\pagestyle{empty}",
        r"\begin{document}",
        rf"\jpheader{{{escape(s['title'])}}}{sub}",
        r"\begin{jianpu}",
        _body(song),
        r"\end{jianpu}",
        r"\end{document}",
        "",
    ])


def bundled_sty() -> str:
    return resources.files("ktab").joinpath("latex", "jianpu.sty").read_text(encoding="utf-8")


def write(song: Song, tex_path: str, fallback_title: str, pdf: bool = True) -> list[str]:
    """Write the .tex (and jianpu.sty if missing) next to it; run pdflatex if asked.
    Returns notes for the user."""
    notes = []
    folder = os.path.dirname(os.path.abspath(tex_path))
    os.makedirs(folder, exist_ok=True)
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write(to_tex(song, fallback_title))
    notes.append(f"wrote {tex_path}")

    sty = os.path.join(folder, "jianpu.sty")
    if not os.path.exists(sty):
        with open(sty, "w", encoding="utf-8") as f:
            f.write(bundled_sty())
        notes.append(f"wrote {sty}")
    elif open(sty, encoding="utf-8").read() != bundled_sty():
        notes.append(f"note: kept your own {sty} (it differs from the one in ktab)")

    if pdf:
        exe = shutil.which("pdflatex")
        if not exe:
            notes.append("pdflatex not found: run it yourself on the .tex file to get the PDF")
            return notes
        name = os.path.basename(tex_path)
        run = subprocess.run([exe, "-interaction=nonstopmode", "-halt-on-error", name],
                             cwd=folder, capture_output=True, text=True)
        stem = os.path.splitext(tex_path)[0]
        log = stem + ".log"
        if run.returncode != 0:
            errs = [l for l in open(log, encoding="latin-1").read().splitlines() if l.startswith("!")]
            raise LatexError("pdflatex failed:\n  " + "\n  ".join(errs[:5] or ["see " + log]))
        for ext in (".aux", ".log"):
            if os.path.exists(stem + ext):
                os.remove(stem + ext)
        notes.append(f"wrote {stem}.pdf")
    return notes
